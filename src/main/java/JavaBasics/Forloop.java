package JavaBasics;

public class Forloop {
    public static void main (String[]args){

        int i =10;

        for( i=0;i<=10;i++)
        {
            if(i%2==1)
            {
                System.out.println(i+"odd");

            }
            else
            {
                System.out.println(i +"even");

            }
        }
    }
}
